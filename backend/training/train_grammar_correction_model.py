# Define a preprocessing function to tokenize inputs and targets.
# We will truncate sequences to a maximum length (e.g., 128 tokens).
max_input_length = 128
max_target_length = 128

# Define a preprocessing function that adapts to the translation field keys.
def preprocess_function(examples):
    # Determine which keys are in use: prefer "eng"/"fra", otherwise "en"/"fr".
    first_translation = examples["translation"][0]
    available_keys = list(first_translation.keys())

    if "eng" in available_keys and "fra" in available_keys:
        src_key = "eng"
        tgt_key = "fra"
    elif "en" in available_keys and "fr" in available_keys:
        src_key = "en"
        tgt_key = "fr"
    else:
        raise ValueError(f"Unrecognized translation keys: {available_keys}")

    inputs = [ex[src_key] for ex in examples["translation"]]
    targets = [ex[tgt_key] for ex in examples["translation"]]
    # Tokenize the input sentences.
    model_inputs = tokenizer(inputs, max_length=max_input_length, truncation=True, padding="max_length")

    # Tokenize the target sentences (using the target tokenizer context).
    with tokenizer.as_target_tokenizer():
        labels = tokenizer(targets, max_length=max_target_length, truncation=True, padding="max_length")

    model_inputs["labels"] = labels["input_ids"]
    return model_inputs

split_dataset = dataset["train"].train_test_split(test_size=0.1, seed=42)
