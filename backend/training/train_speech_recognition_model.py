from datasets import load_dataset, Audio

# Load a small subset
dataset = load_dataset("mozilla-foundation/common_voice_13_0", "fr", split="train[:1%]")
dataset = dataset.remove_columns([col for col in dataset.column_names if col not in ["audio", "sentence"]])
dataset = dataset.cast_column("audio", Audio(sampling_rate=16000))

dataset[0]

import re

chars_to_ignore = '[\,\?\.\!\-\;\:\\"“%\‘’”]'
def clean(batch):
    batch["text"] = re.sub(chars_to_ignore, '', batch["sentence"]).lower().strip()
    return batch

dataset = dataset.map(clean)

from transformers import Wav2Vec2Processor, Wav2Vec2ForCTC

processor = Wav2Vec2Processor.from_pretrained("facebook/wav2vec2-large-xlsr-53-french")
model = Wav2Vec2ForCTC.from_pretrained("facebook/wav2vec2-large-xlsr-53-french")

def prepare(batch):
    audio = batch["audio"]
    batch["input_values"] = processor(audio["array"], sampling_rate=16000).input_values[0]
    batch["labels"] = processor(text=batch["text"]).input_ids
    return batch

dataset = dataset.map(prepare, remove_columns=dataset.column_names)

import torch

from dataclasses import dataclass
from typing import Dict, List, Union

@dataclass
class DataCollatorCTCWithPadding:
    processor: Wav2Vec2Processor
    padding: Union[bool, str] = True

    def __call__(self, features: List[Dict]) -> Dict[str, torch.Tensor]:
        input_features = [{"input_values": f["input_values"]} for f in features]
        label_features = [{"input_ids": f["labels"]} for f in features]

        batch = self.processor.pad(input_features, return_tensors="pt", padding=self.padding)
        with self.processor.as_target_processor():
            labels_batch = self.processor.pad(label_features, return_tensors="pt", padding=self.padding)

        batch["labels"] = labels_batch["input_ids"]
        return batch

data_collator = DataCollatorCTCWithPadding(processor)

# Split the dataset into training and validation
dataset = dataset.train_test_split(test_size=0.1)

train_dataset = dataset["train"]
eval_dataset = dataset["test"]

from transformers import TrainingArguments

training_args = TrainingArguments(
    output_dir="./wav2vec2-french-finetuned",  # Directory to save model output
    per_device_train_batch_size=16,           # Batch size per device
    per_device_eval_batch_size=16,            # Batch size for evaluation
    num_train_epochs=6,                       # Total number of epochs
    logging_steps=100,                        # Log training status every 100 steps
    save_steps=500,                           # Save checkpoint every 500 steps
    evaluation_strategy="steps",              # Evaluate model during training
    eval_steps=500,                           # Evaluate after 500 steps
    learning_rate=2e-5,                       # Set learning rate to 2e-5
    warmup_steps=500,                         # Gradual learning rate increase in first 500 steps
    save_total_limit=2,                       # Limit number of saved checkpoints to 2
    fp16=True,                                # Enable mixed precision for faster training
    max_grad_norm=1.0,                        # Gradient clipping to avoid exploding gradients
    report_to="none",                         # Disable external logging (e.g. wandb)
    load_best_model_at_end=True,              # Load the best model based on evaluation
    metric_for_best_model="eval_wer",         # Use WER to select the best model
    greater_is_better=False,                  # Lower WER is better, so False
)

from transformers import Trainer

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_dataset,
    eval_dataset=eval_dataset,
    tokenizer=processor,
    data_collator=data_collator,
)


trainer.train()

trainer.save_model("fluentique-wav2vec2-fr")
processor.save_pretrained("fluentique-wav2vec2-fr")

